"""Export support ranks and pair limits through the save editor's rules."""

import argparse
import json
from pathlib import Path
import re
import subprocess
import tempfile
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]
PROGRAM = r'''
using System;
using System.Linq;
using System.Text.Json;
using FethEditor.Core;
using SaveEditor;

Database.Init(enmLanguage.en_u);
var presets = SupportRankPresets.Values.Select(rank => new {
  name = rank.Name, points = rank.Points
}).ToArray();
var pairs = Enumerable.Range(0, SupportPairRanks.Count).Select(index => {
  var pair = Database.BinaryDatabase.SupportTalkEntries[index];
  return new {
    index,
    first = pair.Character1 < 0 ? "" : Database.GetUnitName(pair.Character1, NoGender: true),
    second = pair.Character2 < 0 ? "" : Database.GetUnitName(pair.Character2, NoGender: true),
    ranks = SupportPairRanks.AvailableRanks(index),
    maximum = SupportPairRanks.MaxRank(index)
  };
}).ToArray();
Console.WriteLine(JsonSerializer.Serialize(new { presets, pairs }));
'''


def main():
  parser = argparse.ArgumentParser(description=__doc__)
  parser.add_argument('editor', type=Path)
  editor = parser.parse_args().editor.resolve()
  subprocess.run(['dotnet', 'build', str(editor / 'cli/Cli.csproj'),
                  '-c', 'Release', '--nologo'], check=True,
                 stdout=subprocess.DEVNULL)
  dll = editor / 'cli/bin/Release/net10.0/FethEditor.Core.dll'
  with tempfile.TemporaryDirectory(prefix='feth-support-export-') as temporary:
    directory = Path(temporary)
    project = directory / 'Export.csproj'
    project.write_text(
      '<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup>'
      '<OutputType>Exe</OutputType><TargetFramework>net10.0</TargetFramework>'
      '</PropertyGroup><ItemGroup><Reference Include="FethEditor.Core">'
      f'<HintPath>{escape(str(dll))}</HintPath>'
      '</Reference></ItemGroup></Project>\n')
    (directory / 'Program.cs').write_text(PROGRAM)
    subprocess.run(['dotnet', 'build', str(project), '-c', 'Release', '--nologo'],
                   check=True, stdout=subprocess.DEVNULL)
    data = json.loads(subprocess.check_output(
      ['dotnet', str(directory / 'bin/Release/net10.0/Export.dll')], text=True))

  # Keep memory indices anchored to the original overlay's pair table.
  catalog = (ROOT / 'source/core/catalog.cpp').read_text().split('SUPPORT_LIST =')[1]
  pairs = re.findall(r'\{"([^"]+)", "([^"]+)"\}', catalog)
  for index, (first, second) in enumerate(pairs):
    entry = data['pairs'][index]
    assert (first, second) == (entry['first'], entry['second']), (index, entry)

  revision = subprocess.check_output(
    ['git', '-C', str(editor), 'rev-parse', 'HEAD'], text=True).strip()
  source = {'repository': 'https://github.com/hashcade/feth-save-editor',
            'revision': revision,
            'rules': ['core/SupportRankPresets.cs', 'core/SupportPairRanks.cs']}
  (ROOT / 'assets/support-ranks.json').write_text(
    '{\n  "source": ' + json.dumps(source) + ',\n  "presets": '
    + json.dumps(data['presets']) + ',\n  "pairs": [\n'
    + ',\n'.join('    ' + json.dumps(entry) for entry in data['pairs'])
    + '\n  ]\n}\n')

  lines = [
    '// Generated by scripts/export_supports.py. Do not edit.',
    '// Support rules from hashcade/feth-save-editor (MIT).',
    '#include "feth/core/supports.hpp"', '', 'namespace feth::core {',
    'namespace {', 'constexpr SupportRank kRanks[] = {',
  ]
  for rank in data['presets']:
    lines.append(f'  {{"{rank["name"]}", {rank["points"]}}},')
  lines += ['};', 'constexpr std::uint8_t kPairRanks[] = {']
  ranks = [rank['name'] for rank in data['presets'][1:]]
  for pair in data['pairs']:
    mask = sum(1 << bit for bit, rank in enumerate(ranks) if rank in pair['ranks'])
    lines.append(f'  0x{mask:02X}, // {pair["index"]}: {pair["first"]} / {pair["second"]}')
  lines += [
    '};', '} // namespace', '',
    'std::span<const SupportRank> support_rank_presets() { return kRanks; }',
    'std::uint8_t support_rank_mask(std::size_t index) {',
    '  return index < std::size(kPairRanks) ? kPairRanks[index] : 0;',
    '}', '', '} // namespace feth::core', '',
  ]
  (ROOT / 'source/generated/support_catalog.cpp').write_text('\n'.join(lines))
  print(f'Exported support ranks for {len(data["pairs"])} pairs')


if __name__ == '__main__':
  main()
