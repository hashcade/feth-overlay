"""Export playable class eligibility using the save editor's existing rules."""

import argparse
import json
from pathlib import Path
import subprocess
import tempfile
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]

PROGRAM = r'''
using System;
using System.Collections.Generic;
using System.Linq;
using System.Text.Json;
using FethEditor.Core;
using SaveEditor;

Database.Init(enmLanguage.en_u);
var entries = new List<object>();
for (int unit = 0; unit < Database.BinaryDatabase.CharacterEntries.Count; unit++) {
  int record = ClassEligibility.RecordForUnit(unit);
  if (record < 0) continue;
  int[] classes = Enumerable.Range(0, Database.MAX_CLASS)
    .Where(id => ClassEligibility.IsAvailable(record, id)).ToArray();
  entries.Add(new { unit, record, name = Database.GetUnitName(unit), classes });
}
Console.WriteLine(JsonSerializer.Serialize(entries));
'''


def main():
  parser = argparse.ArgumentParser(description=__doc__)
  parser.add_argument('editor', type=Path)
  editor = parser.parse_args().editor.resolve()
  subprocess.run(['dotnet', 'build', str(editor / 'cli/Cli.csproj'),
                  '-c', 'Release', '--nologo'], check=True,
                 stdout=subprocess.DEVNULL)
  dll = editor / 'cli/bin/Release/net10.0/FethEditor.Core.dll'
  with tempfile.TemporaryDirectory(prefix='feth-class-export-') as temporary:
    directory = Path(temporary)
    project = directory / 'Export.csproj'
    project.write_text(
      '<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup>'
      '<OutputType>Exe</OutputType><TargetFramework>net10.0</TargetFramework>'
      '</PropertyGroup><ItemGroup><Reference Include="FethEditor.Core">'
      f'<HintPath>{escape(str(dll))}</HintPath>'
      '</Reference></ItemGroup></Project>\n')
    (directory / 'Program.cs').write_text(PROGRAM)
    subprocess.run(['dotnet', 'build', str(project), '-c', 'Release', '--nologo'],
                   check=True, stdout=subprocess.DEVNULL)
    entries = json.loads(subprocess.check_output(
      ['dotnet', str(directory / 'bin/Release/net10.0/Export.dll')], text=True))

  revision = subprocess.check_output(
    ['git', '-C', str(editor), 'rev-parse', 'HEAD'], text=True).strip()
  source = {'repository': 'https://github.com/hashcade/feth-save-editor',
            'revision': revision, 'rules': 'core/ClassEligibility.cs'}
  (ROOT / 'assets/class-eligibility.json').write_text(
    '{\n  "source": ' + json.dumps(source) + ',\n  "characters": [\n'
    + ',\n'.join('    ' + json.dumps(entry, ensure_ascii=False) for entry in entries)
    + '\n  ]\n}\n')

  lines = [
    '// Generated by scripts/export_classes.py. Do not edit.',
    '// Eligibility from hashcade/feth-save-editor (MIT).',
    '#include "feth/core/classes.hpp"', '', 'namespace feth::core {',
    'namespace {',
    'struct Eligibility { CharacterId character; std::uint64_t base, special; };',
    'constexpr Eligibility kEligibility[] = {',
  ]
  for entry in entries:
    base = sum(1 << kind for kind in entry['classes'] if kind < 64)
    special = sum(1 << (kind - 84) for kind in entry['classes'] if kind >= 84)
    lines.append(f'  {{{entry["unit"]}, 0x{base:X}ULL, 0x{special:X}ULL}},')
  lines.extend([
    '};', '} // namespace', '',
    'ClassUnlocks available_class_unlocks(CharacterId character) {',
    '  for (const auto& entry : kEligibility) {',
    '    if (entry.character == character)',
    '      return {ClassUnlockBitset(entry.base), ClassUnlockBitset(entry.special)};',
    '  }', '  return {};', '}', '', '} // namespace feth::core', '',
  ])
  (ROOT / 'source/generated/class_catalog.cpp').write_text('\n'.join(lines))
  print(f'Exported class eligibility for {len(entries)} character IDs')


if __name__ == '__main__':
  main()
